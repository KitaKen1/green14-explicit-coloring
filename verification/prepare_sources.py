"""Reproduce the exact FC challenge and the pasteable Lean source."""

from argparse import ArgumentParser
from hashlib import sha256
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
REFERENCE = ROOT / "verification" / "reference"
HASHES = {
    "14.lean": "6732198534cb591b152be1e5557285ebac74c36b63fc2749b339f5349adbae49",
    "AP.lean": "62f0a0987d49c5dbfd7b4f82a4f3dd4faba7ad545c676df06d0cda009567b5c3",
}


def upstream_challenge():
    for name, expected in HASHES.items():
        actual = sha256((REFERENCE / name).read_bytes()).hexdigest()
        if actual != expected:
            raise ValueError(f"{name} differs from the pinned FC source")

    upstream_ap = (REFERENCE / "AP.lean").read_text(encoding="utf-8")
    local_ap = (ROOT / "lean/Green14/Statement.lean").read_text(encoding="utf-8")
    for name in ("Set.IsAPOfLengthWith", "Set.IsAPOfLength"):
        pattern = rf"^def {re.escape(name)} .*?(?=\n\n)"
        source, = re.findall(pattern, upstream_ap, re.M | re.S)
        local, = re.findall(pattern, local_ap, re.M | re.S)
        # The pinned file declares these binders in a shared variable command.
        source = source.replace(f"def {name}", f"def {name} {{α : Type*}} [AddCommMonoid α]", 1)
        if source.split() != local.split():
            raise ValueError(f"{name} differs from the pinned FC definition")

    upstream = (REFERENCE / "14.lean").read_text(encoding="utf-8")
    answer, = re.findall(r"^def green_14_variant_2r2\.answer [^\n]+\n", upstream, re.M)
    theorem, = re.findall(r"^theorem green_14_variant_2r2 :\n.*?^  sorry\n", upstream, re.M | re.S)
    return (
        "-- Generated by verification/prepare_sources.py from the pinned FC snapshot.\n"
        "module\n\n"
        "public import Green14.Statement\n"
        "public import Green14.Parameters\n\n"
        "@[expose] public section\n\n"
        "set_option warn.sorry false\n\n"
        "namespace Green14\n\n"
        "open Set\n\n"
        + answer + "\n" + theorem + "\n"
        # This elaboration checks the normalized wrapper used in the reduction.
        "example : ValidAnswer green_14_variant_2r2.answer := green_14_variant_2r2\n\n"
        "theorem Review.answer_parameter : green_14_variant_2r2.answer.1 = r := by sorry\n\n"
        "end Green14\n"
    )


def standalone():
    names = ["Statement", "Parameters", "Red", "Cover", "Greedy", "Cubic", "Moment",
             "Singer", "Discrepancy", "GreedyFacts", "Covering", "Final"]
    files = [ROOT / "lean" / "Green14" / f"{name}.lean" for name in names]
    files.append(ROOT / "lean" / "Green14.lean")
    files.append(ROOT / "lean" / "Comparator" / "Candidate.lean")
    imports = []
    bodies = []
    for file in files:
        lines = file.read_text(encoding="utf-8").splitlines()
        for line in lines:
            if line.startswith("public import Mathlib.") and line not in imports:
                imports.append(line)
        body = "\n".join(line for line in lines
                         if line not in ("module", "@[expose] public section")
                         and not line.startswith("public import "))
        bodies.append(body.strip())
    return "-- Generated by verification/prepare_sources.py.\nmodule\n\n" + "\n\n".join(
        ["\n".join(imports), "@[expose] public section", *bodies]
    ) + "\n"


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify the generated files")
    options = parser.parse_args()
    outputs = {
        ROOT / "lean/Comparator/Upstream.lean": upstream_challenge(),
        ROOT / "lean/Green14Lean4Web.lean": standalone(),
    }
    for file, content in outputs.items():
        if options.check:
            if not file.is_file() or file.read_text(encoding="utf-8") != content:
                raise SystemExit(f"{file.relative_to(ROOT)} is out of date.")
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
